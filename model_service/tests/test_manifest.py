"""Guards the committed manifest. Runs without the Kaggle data — it reads only the
tracked manifest.csv — so it runs in CI and on every teammate's machine.

If this fails after someone edits manifest.csv by hand, that is the point.
The manifest is generated by make_manifest.py and should only change via that script.
"""

from pathlib import Path

import pandas as pd

from model_service.knee_model.make_manifest import FINDING_COLUMNS
from shared.schema import FINDINGS

MANIFEST = Path(__file__).resolve().parents[1] / "knee_model" / "manifest.csv"


def test_manifest_exists() -> None:
    assert MANIFEST.exists(), "run: python -m model_service.knee_model.make_manifest"


def test_manifest_contract() -> None:
    m = pd.read_csv(MANIFEST)
    assert list(m.columns) == ["study_id", "label_source"]
    assert m["study_id"].is_unique
    assert set(m["label_source"]) == {"gold", "weak"}


def test_manifest_counts() -> None:
    # 58 gold is a property of train.csv; 250 weak is the Step 2 decision.
    m = pd.read_csv(MANIFEST)
    counts = m["label_source"].value_counts()
    assert counts["gold"] == 58
    assert counts["weak"] == 250
    assert len(m) == 308


def test_finding_columns_match_schema() -> None:
    # Person 2's label CSV must follow shared.schema.FINDINGS. The manifest script
    # uses the same 12 names in the same order to read train.csv. Keep them locked together.
    assert FINDING_COLUMNS == FINDINGS
